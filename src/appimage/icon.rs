//! Synthused-PNG icon generation (v1 pipeline).
//!
//! v1 draws an accent-filled 256×256 PNG with the first non-whitespace letter
//! of the display name using an inline 8×8 bitmap font. Embedded `.DirIcon`
//! extraction ships in v2 and will replace this body with an `unsquashfs` call
//! against the offset from [`super::elf_offset::find`].

use std::path::{Path, PathBuf};

use image::{ImageBuffer, ImageFormat, Rgba};

use crate::error::Result;

/// Synthesized-icon background. v1 uses the Libadwaita default blue for
/// stability across libadwaita versions (the dynamic `accent_color_rgba()` is
/// only available with the `v1_6` feature, which would force a newer
/// `libadwaita-1` at build time than every CI runner carries).
pub const DEFAULT_ACCENT: [u8; 3] = [0x35, 0x84, 0xe4];

/// Picks the accent color for a synthesized icon. v1 always returns the
/// Libadwaita default; v2 will read the user's accent from `StyleManager`.
fn accent_color() -> [u8; 3] {
    DEFAULT_ACCENT
}

/// Returns the absolute path of the written icon PNG. Parent directories are
/// created. `dest_path` is the final path.
pub fn synthesize_icon(display_name: &str, dest_path: &Path) -> Result<PathBuf> {
    if let Some(parent) = dest_path.parent() {
        std::fs::create_dir_all(parent)?;
    }
    let accent = accent_color();
    let mut img: ImageBuffer<Rgba<u8>, Vec<u8>> = ImageBuffer::new(256, 256);
    for p in img.pixels_mut() {
        *p = Rgba([accent[0], accent[1], accent[2], 255]);
    }

    let ch = display_name
        .chars()
        .find(|c| !c.is_whitespace())
        .map(to_glyph_char)
        .unwrap_or('?');
    draw_letter(&mut img, ch);

    img.save_with_format(dest_path, ImageFormat::Png)?;
    Ok(dest_path.to_path_buf())
}

/// Maps a character to the glyph set (A..Z, 0..9, else `?`).
fn to_glyph_char(c: char) -> char {
    match c {
        'a'..='z' => c.to_ascii_uppercase(),
        'A'..='Z' | '0'..='9' => c,
        _ => '?',
    }
}

/// Draws a single 8×8 glyph scaled to fill the central 128×128 area of the
/// 256×256 canvas (each font pixel → 16×16 device pixels). Drawing at native
/// 1:1 made the letter invisible at 32px display — each font pixel ended up
/// ~0.125 device pixels.
fn draw_letter(img: &mut ImageBuffer<Rgba<u8>, Vec<u8>>, c: char) {
    let font: &[[u8; 8]; 8] = match c {
        'A'..='Z' => FONT_AZ[c as usize - b'A' as usize],
        '0'..='9' => FONT_NUMS[c as usize - b'0' as usize],
        _ => &FONT_Q,
    };
    let white = Rgba([255u8, 255u8, 255u8, 255u8]);
    // Each font pixel becomes a 16x16 block. Center the 128x128 glyph
    // region:  (256 - 128) / 2 = 64, so glyph spans x=64..192, y=64..192.
    const SCALE: u32 = 16;
    const OFFSET: u32 = 64;
    for (row_idx, cells) in font.iter().enumerate() {
        for (col_idx, on) in cells.iter().enumerate() {
            if *on == 1 {
                let bx = col_idx as u32 * SCALE + OFFSET;
                let by = row_idx as u32 * SCALE + OFFSET;
                for dy in 0..SCALE {
                    for dx in 0..SCALE {
                        img.put_pixel(bx + dx, by + dy, white);
                    }
                }
            }
        }
    }
}


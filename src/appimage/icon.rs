#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn synthesize_writes_256x256_png() {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("icons").join("a.png");
        let p = synthesize_icon("Test App", &path).unwrap();
        assert_eq!(p, path);
        let img = image::open(&path).unwrap();
        assert_eq!(img.width(), 256);
        assert_eq!(img.height(), 256);
    }

    #[test]
    fn glyph_mapping_folds_case() {
        assert_eq!(to_glyph_char('a'), 'A');
        assert_eq!(to_glyph_char('Z'), 'Z');
        assert_eq!(to_glyph_char('5'), '5');
        assert_eq!(to_glyph_char('@'), '?');
    }
}
